#!/usr/bin/env python3
"""Generate inproc/nfd_tables.go: the Unicode NFD data (canonical decomposition
per rune + canonical combining classes) that lets go-piper normalize text
exactly like piper without the golang.org/x/text module dependency.

It only runs once when the library is prepared/generated (not at build or run
time). Regenerate after a Unicode bump:

    python3 scripts/gennfd.py        # run from the module root (writes inproc/nfd_tables.go)

Hangul syllables are excluded here: their decomposition is algorithmic and
lives in inproc/nfd.go.
"""
import sys
import unicodedata as ud

decomp = []
ccc = []
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF:      # surrogates
        continue
    if 0xAC00 <= cp <= 0xD7A3:      # Hangul syllables (algorithmic)
        continue
    ch = chr(cp)
    d = ud.normalize("NFD", ch)
    if d != ch:
        decomp.append((cp, [ord(c) for c in d]))
    else:
        k = ud.combining(ch)
        if k:
            ccc.append((cp, k))

out = []
w = out.append
w("// Code generated by scripts/gennfd.py; DO NOT EDIT.")
w("//")
w("// Unicode NFD data. It replaces golang.org/x/text/unicode/norm so the")
w("// module stays dependency-free. Regenerate: python3 scripts/gennfd.py")
w("package inproc")
w("")
w("// canonicalDecomp maps a rune to its full NFD decomposition.")
w("var canonicalDecomp = map[rune][]rune{")
for cp, seq in decomp:
    w("\t0x%04X: {%s}," % (cp, ", ".join("0x%04X" % x for x in seq)))
w("}")
w("")
w("// combiningClass maps a rune to its canonical combining class; runes that")
w("// are absent have class 0.")
w("var combiningClass = map[rune]uint8{")
for cp, k in ccc:
    w("\t0x%04X: %d," % (cp, k))
w("}")
w("")

with open("inproc/nfd_tables.go", "w") as f:
    f.write("\n".join(out))
sys.stderr.write("wrote inproc/nfd_tables.go: decomp=%d ccc=%d (Unicode %s)\n"
                 % (len(decomp), len(ccc), ud.unidata_version))
